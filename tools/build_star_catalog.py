"""Build the night sky's star catalogue from Tiefenkontakt.

Tiefenkontakt (MIT, the same author) packs the 986 stars of the Yale Bright
Star Catalogue, 5th revised edition (Hoffleit & Warren 1991, VizieR V/50,
public domain), brighter than visual magnitude 4.6, in
``apps/client/src/widgets/sea3d/star-catalog.ts``: six bytes a star,
brightest first, RA and Dec as uint16 (0..360 deg, -90..+90 deg), V as
(V + 1.5) * 40 and B-V as (B-V + 0.4) * 80, one byte each.  This tool
copies that block unchanged into

* ``data/sky/bright_stars.json`` (read by ``src/ui/stars.py``) and
* ``data/commander/js/views/star-catalog.js`` (the browser's twin),

so both games show the same stars.

    python3 tools/build_star_catalog.py PATH/TO/tiefenkontakt [--commit SHA]
"""

from __future__ import annotations

import argparse
import json
import os
import re
import subprocess

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SOURCE = os.path.join("apps", "client", "src", "widgets", "sea3d", "star-catalog.ts")
JSON_OUT = os.path.join(ROOT, "data", "sky", "bright_stars.json")
JS_OUT = os.path.join(ROOT, "data", "commander", "js", "views", "star-catalog.js")
PROVENANCE = ("Yale Bright Star Catalogue, 5th revised edition (Hoffleit & Warren 1991, "
              "VizieR V/50, public domain, NASA/ADC), stars brighter than V 4.6, close pairs "
              "merged; packed by Tiefenkontakt (MIT)")


def read_catalog(checkout: str) -> tuple:
    text = open(os.path.join(checkout, SOURCE), encoding="utf-8").read()
    count = int(re.search(r"STAR_COUNT\s*=\s*(\d+)", text).group(1))
    block = text[text.index("STARS_B64"):]
    b64 = "".join(re.findall(r"'([A-Za-z0-9+/=]*)'", block))
    if len(b64) * 3 // 4 - b64.count("=") != count * 6:
        raise SystemExit("unexpected catalogue length")
    return count, b64


def write(count: int, b64: str, commit: str) -> None:
    data = {"schema": 1, "count": count, "stars_b64": b64,
            "provenance": {"catalogue": PROVENANCE, "tiefenkontakt_commit": commit}}
    with open(JSON_OUT, "w", encoding="utf-8") as target:
        json.dump(data, target, separators=(",", ":"), sort_keys=True)
        target.write("\n")
    lines = [b64[i:i + 120] for i in range(0, len(b64), 120)]
    with open(JS_OUT, "w", encoding="utf-8") as target:
        target.write("// Generated by tools/build_star_catalog.py from Tiefenkontakt; do not edit.\n"
                     f"// {PROVENANCE}.\n"
                     "// Six bytes a star, brightest first: RA, Dec (uint16), (V + 1.5) * 40, "
                     "(B-V + 0.4) * 80.\n"
                     f"export const STAR_COUNT = {count};\n"
                     "export const STARS_B64 =\n  "
                     + " +\n  ".join(f"'{line}'" for line in lines) + ";\n")


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("checkout")
    parser.add_argument("--commit", default=None)
    args = parser.parse_args(argv)
    commit = args.commit or subprocess.run(["git", "-C", args.checkout, "rev-parse", "HEAD"],
                                           capture_output=True, text=True).stdout.strip()
    count, b64 = read_catalog(args.checkout)
    write(count, b64, commit)
    print("wrote", count, "stars")


if __name__ == "__main__":
    main()
